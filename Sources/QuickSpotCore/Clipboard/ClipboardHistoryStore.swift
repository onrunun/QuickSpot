import AppKit
import Foundation

/// One persisted text snippet captured from macOS clipboard history.
public struct ClipboardEntry: Identifiable, Codable, Equatable, Sendable {
    public let id: String
    public let text: String
    public let timestamp: TimeInterval
    public let sourceApp: String?

    public init(id: String = UUID().uuidString, text: String, timestamp: TimeInterval = Date().timeIntervalSince1970, sourceApp: String? = nil) {
        self.id = id
        self.text = text
        self.timestamp = timestamp
        self.sourceApp = sourceApp
    }
}

/// Privacy-conscious, zero-allocation-when-idle clipboard history store with persistence and instant search.
public final class ClipboardHistoryStore: @unchecked Sendable {
    public static let maxEntries = 150
    public static let maxCharactersPerEntry = 65_536

    private static let enabledKey = "QuickSpot.clipboard.enabled"

    /// Standard macOS pasteboard markers used by password managers and transient tools.
    public static let ignoredPasteboardTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType"
    ]

    /// Bundle ID prefixes of password/credential managers whose clipboard writes must never be recorded.
    public static let ignoredBundleIDPrefixes: [String] = [
        "com.apple.Passwords",
        "com.apple.keychainaccess",
        "com.1password",
        "com.agilebits",
        "com.bitwarden",
        "com.lastpass",
        "org.keepassxc",
        "com.dashlane"
    ]

    private let lock = NSLock()
    private let storageURL: URL
    private let defaults: UserDefaults
    private var entries: [ClipboardEntry] = []
    private var lastObservedChangeCount: Int = -1
    private var timer: Timer?

    public init(storageURL: URL? = nil, defaults: UserDefaults = .standard) {
        self.storageURL = storageURL ?? Self.defaultStorageURL()
        self.defaults = defaults
        self.entries = Self.loadEntries(from: self.storageURL)
    }

    deinit {
        stopMonitoring()
    }

    public static func defaultStorageURL() -> URL {
        let base = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask).first
            ?? URL(fileURLWithPath: NSHomeDirectory()).appendingPathComponent("Library/Application Support")
        return base.appendingPathComponent("QuickSpot/clipboard-history.json")
    }

    public var isEnabled: Bool {
        get {
            lock.lock()
            defer { lock.unlock() }
            return defaults.object(forKey: Self.enabledKey) as? Bool ?? true
        }
        set {
            lock.lock()
            defaults.set(newValue, forKey: Self.enabledKey)
            lock.unlock()
            if !newValue {
                stopMonitoring()
            } else {
                startMonitoring()
            }
        }
    }

    public var count: Int {
        lock.lock()
        defer { lock.unlock() }
        return entries.count
    }

    /// Starts lightweight changeCount monitoring on the main run loop (~0.75s interval).
    public func startMonitoring() {
        guard isEnabled else { return }
        DispatchQueue.main.async { [weak self] in
            guard let self, self.timer == nil, self.isEnabled else { return }
            self.lastObservedChangeCount = NSPasteboard.general.changeCount
            let t = Timer(timeInterval: 0.75, repeats: true) { [weak self] _ in
                self?.pollGeneralPasteboard()
            }
            t.tolerance = 0.25
            RunLoop.main.add(t, forMode: .common)
            self.timer = t
        }
    }

    public func stopMonitoring() {
        if Thread.isMainThread {
            timer?.invalidate()
            timer = nil
        } else {
            DispatchQueue.main.async { [weak self] in
                self?.timer?.invalidate()
                self?.timer = nil
            }
        }
    }

    public func pollGeneralPasteboard() {
        guard isEnabled else { return }
        let pb = NSPasteboard.general
        let currentCount = pb.changeCount
        guard currentCount != lastObservedChangeCount else { return }
        lastObservedChangeCount = currentCount

        let frontApp = NSWorkspace.shared.frontmostApplication
        let types = Set((pb.types ?? []).map(\.rawValue))
        guard Self.shouldRecord(pasteboardTypes: types, sourceBundleID: frontApp?.bundleIdentifier) else {
            return
        }
        guard let text = pb.string(forType: .string) else { return }
        recordText(text, sourceApp: frontApp?.localizedName)
    }

    /// Pure privacy filter check for pasteboard marker types and source application bundle ID.
    public static func shouldRecord(pasteboardTypes: Set<String>, sourceBundleID: String?) -> Bool {
        if !ignoredPasteboardTypes.isDisjoint(with: pasteboardTypes) {
            return false
        }
        if let bid = sourceBundleID?.lowercased() {
            for prefix in ignoredBundleIDPrefixes where bid.hasPrefix(prefix.lowercased()) {
                return false
            }
        }
        return true
    }

    /// Records a text snippet, deduplicating by moving identical entries to the top.
    @discardableResult
    public func recordText(_ raw: String, sourceApp: String? = nil, timestamp: TimeInterval = Date().timeIntervalSince1970) -> Bool {
        guard isEnabled else { return false }
        let trimmedCheck = raw.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmedCheck.isEmpty, raw.count <= Self.maxCharactersPerEntry else { return false }

        lock.lock()
        entries.removeAll { $0.text == raw }
        entries.insert(ClipboardEntry(text: raw, timestamp: timestamp, sourceApp: sourceApp), at: 0)
        if entries.count > Self.maxEntries {
            entries = Array(entries.prefix(Self.maxEntries))
        }
        let snapshot = entries
        lock.unlock()

        persist(snapshot)
        return true
    }

    /// Marks text copied by QuickSpot itself so it promotes cleanly without duplicate insertion.
    public func promoteCopiedText(_ text: String) {
        lock.lock()
        lastObservedChangeCount = NSPasteboard.general.changeCount
        lock.unlock()
        recordText(text, sourceApp: "QuickSpot")
    }

    public func delete(entryID: String) {
        lock.lock()
        let before = entries.count
        entries.removeAll { $0.id == entryID }
        let changed = entries.count != before
        let snapshot = entries
        lock.unlock()
        if changed { persist(snapshot) }
    }

    public func clearAll() {
        lock.lock()
        entries.removeAll()
        lock.unlock()
        persist([])
    }

    public func allEntries(limit: Int = 30) -> [ClipboardEntry] {
        lock.lock()
        defer { lock.unlock() }
        return Array(entries.prefix(limit))
    }

    /// Searches clipboard history (empty query returns most recent entries in chronological order).
    public func search(query: String, limit: Int = 20) -> [SearchItem] {
        lock.lock()
        let snapshot = entries
        lock.unlock()

        let trimmed = query.trimmingCharacters(in: .whitespacesAndNewlines)
        if trimmed.isEmpty {
            return snapshot.prefix(limit).enumerated().map { idx, entry in
                makeSearchItem(for: entry, score: max(500, 950 - idx * 8))
            }
        }

        let normQuery = FuzzyMatcher.normalize(trimmed)
        let tokens = normQuery.split(whereSeparator: \.isWhitespace).map(String.init)
        var scored: [(entry: ClipboardEntry, score: Int)] = []

        for (idx, entry) in snapshot.enumerated() {
            let normText = FuzzyMatcher.normalize(entry.text)
            let normSource = entry.sourceApp.map(FuzzyMatcher.normalize) ?? ""
            guard tokens.allSatisfy({ normText.contains($0) || normSource.contains($0) }) else {
                continue
            }
            let firstLine = Self.compactTitle(for: entry.text)
            let titleScore = FuzzyMatcher.score(query: trimmed, candidate: firstLine) ?? 640
            let recencyBonus = max(0, 60 - idx * 2)
            scored.append((entry, min(titleScore + recencyBonus, 980)))
        }

        scored.sort {
            if $0.score != $1.score { return $0.score > $1.score }
            return $0.entry.timestamp > $1.entry.timestamp
        }
        return scored.prefix(limit).map { makeSearchItem(for: $0.entry, score: $0.score) }
    }

    private func makeSearchItem(for entry: ClipboardEntry, score: Int) -> SearchItem {
        let title = Self.compactTitle(for: entry.text)
        let dateStr = Date(timeIntervalSince1970: entry.timestamp).formatted(
            Date.FormatStyle(date: .abbreviated, time: .shortened).locale(L10n.currentLocale)
        )
        let lines = entry.text.components(separatedBy: .newlines).count
        let sizeHint = lines > 1
            ? L10n.format("clipboard.size_lines_chars", lines, entry.text.count)
            : L10n.format("clipboard.size_chars", entry.text.count)
        let parts = [entry.sourceApp, dateStr, sizeHint].compactMap { $0 }
        return SearchItem(
            id: "clip:\(entry.id)",
            title: title,
            subtitle: parts.joined(separator: " · "),
            category: .quickAction,
            sfSymbol: "doc.on.clipboard",
            score: score,
            action: .copyText(entry.text),
            matchedSnippet: entry.text,
            matchSource: .clipboard
        )
    }

    private static func compactTitle(for text: String) -> String {
        let singleLine = text
            .replacingOccurrences(of: "\r\n", with: " ")
            .replacingOccurrences(of: "\n", with: " ")
            .replacingOccurrences(of: "\t", with: " ")
            .split(whereSeparator: \.isWhitespace)
            .joined(separator: " ")
        if singleLine.count <= 84 { return singleLine }
        return String(singleLine.prefix(83)) + "…"
    }

    private static func loadEntries(from url: URL) -> [ClipboardEntry] {
        guard let data = try? Data(contentsOf: url),
              let decoded = try? JSONDecoder().decode([ClipboardEntry].self, from: data) else {
            return []
        }
        return Array(decoded.prefix(maxEntries))
    }

    private func persist(_ snapshot: [ClipboardEntry]) {
        let targetURL = storageURL
        DispatchQueue.global(qos: .utility).async {
            let dir = targetURL.deletingLastPathComponent()
            try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
            if let data = try? JSONEncoder().encode(snapshot) {
                try? data.write(to: targetURL, options: .atomic)
                try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: targetURL.path)
            }
        }
    }
}
